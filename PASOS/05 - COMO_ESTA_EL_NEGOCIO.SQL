'1 - TOTAL DE VENTAS'
        SELECT ROUND (SUM (SALES),2)
        FROM VENTAS_SS;

'2 - TOTAL DE GANANCIAS'
        SELECT ROUND (SUM (PROFIT),2) AS GANANCIAS_TOTALES
        FROM VENTAS_SS;

'3 - TOTAL DE PRODUCTOS VENDIDOS'
        SELECT SUM(QUANTITY) AS CANTIDAD_TOTAL
        FROM VENTAS_SS;

'4 - TOTAL DE CLIENTES'
        SELECT COUNT
        (DISTINCT CUSTOMER_ID)
        FROM VENTAS_SS;

'5 - TOTAL DE ORDENES'
        SELECT COUNT(ORDER_ID) 
        AS TOTAL_DE_ORDENES
        FROM VENTAS_SS;

'5 - TOTAL DE ORDENES UNICAS'
        SELECT COUNT(DISTINCT ORDER_ID) 
        AS TOTAL_DE_ORDENES_UNICAS
        FROM VENTAS_SS;