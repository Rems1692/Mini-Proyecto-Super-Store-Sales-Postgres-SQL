1 - VENTAS POR AÑO
    ALTER TABLE VENTAS_SS
    ALTER COLUMN ORDER_DATE 
    TYPE DATE USING ORDER_DATE::DATE; 'CAMBIA EL FORMATO A DATE'

    SELECT 
    EXTRACT(YEAR FROM ORDER_DATE) AS YEAR,
    TO_CHAR(SUM(SALES),'9G999G999D99') AS VENTAS_TOTALES '9 REPRESENTA UN DIGITO NUMERICO, 
    G AÑADE SEPARADORES DE MILES, D AÑADE SEPARADOR DE DECIMALES'
    FROM VENTAS_SS
    GROUP BY YEAR
    ORDER BY YEAR DESC; 

2 - VENTAS POR MES CONSOLIDADO DE LAS VENTAS POR MES
    SELECT
    TO_CHAR(ORDER_DATE, 'FMMONTH') AS MONTH_TEXT, 'FM ELIMINA ESPACIOS'
    EXTRACT(MONTH FROM ORDER_DATE) AS MONTH_NUM,
    TO_CHAR(SUM(SALES,'9G999G999D99') AS VENTAS_TOTALES
    FROM VENTAS_SS
    GROUP BY MONTH_TEXT, MONTH_NUM
    ORDER BY MONTH_NUM;

3 - VENTAS POR MES Y AÑO
    SELECT
    EXTRACT(YEAR FROM ORDER_DATE) AS YEAR,
    TO_CHAR(ORDER_DATE, 'FMMONTH') AS MONTH_TEXT,
    EXTRACT(MONTH FROM ORDER_DATE) AS MONTH_NUM,
    SUM(SALES) AS VENTAS_TOTALES
    FROM VENTAS_SS
    GROUP BY YEAR, MONTH_TEXT, MONTH_NUM
    ORDER BY YEAR, MONTH_NUM;

