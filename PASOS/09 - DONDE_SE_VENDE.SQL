1 - ALTER TABLE VENTAS_SS
    ADD COLUMN REGION VARCHAR(50),
    ADD COLUMN STATE VARCHAR(50),
    ADD COLUMN CITY VARCHAR(50);

2 - UPDATE VENTAS_SS V
    SET
    REGION = S.REGION,
    STATE = S.STATE, 
    CITY = S.CITY
    FROM 
    SUPERSTORE_RAW S
    WHERE 
    V.ORDER_ID = S.ORDER_ID          'SE USO UPDATE PORQUE MODIFICA LAS FILAS QUE YA EXISTEN EN LA TABLA VENTAS_SS'
    AND V.PRODUCT_ID = S.PRODUCT_ID; 'MIENTRAS QUE INSERT CREARIA NUEVAS FILAS Y DUPLICARIA LOS REGISTROS'

3 - ¿QUEDO ALGUN VALOR NULO?
    SELECT
    COUNT(*) AS TOTAL_REGISTROS
    FROM VENTAS_SS
    WHERE
    REGION IS NULL
    OR STATE IS NULL
    OR CITY IS NULL; 'CON ESTO VERIFICO SI TENGO ALGUN VALOR NULO EN LAS COLUMNAS REGION, STATE O CITY'

4 - VALIDAR LAS REGIONES SI ESTAN COMPLETAS
    SELECT
    REGION,
    COUNT(*) AS TOTAL_REGISTROS
    FROM VENTAS_SS
    GROUP BY REGION
    ORDER BY TOTAL_REGISTROS DESC;

5 - ¿QUÉ REGIÓN GENERA MÁS VENTAS?
    SELECT
    REGION,
    ROUND(SUM(SALES),2) AS VENTAS_TOTALES
    FROM VENTAS_SS
    GROUP BY REGION
    ORDER BY VENTAS_TOTALES DESC;

6 - ¿QUÉ REGIÓN GENERA MÁS GANANCIAS?
    SELECT
    REGION,
    ROUND(SUM(PROFIT),2) AS GANANCIAS_TOTALES
