JOIN PRODUCTOS_SSL P
ON V.PRODUCT_ID = P.PRODUCT_ID
WHERE P.CATEGORY = 'Furniture'
GROUP BY
P.SUB_CATEGORY
ORDER BY VENTAS_TOTALES DESC

