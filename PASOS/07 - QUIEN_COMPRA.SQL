1 - ¿CUÁNTOS CLIENTES ÚNICOS TIENE LA EMPRESA?
    SELECT
    COUNT (DISTINCT CUSTOMER_ID) AS CLIENTE_UNICO
    FROM CLIENTES_SS

    -- La empresa ha registrado 793 clientes distintos en el período analizado.

2 - ¿CUÁNTAS ÓRDENES REALIZÓ CADA CLIENTE?
    SELECT 
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    COUNT (V.ORDER_ID) 
        AS CANTIDAD_DE_ORDENES
    FROM CLIENTES_SS C
    JOIN VENTAS_SS V
        ON V.CUSTOMER_ID = C.CUSTOMER_ID
    GROUP BY 
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
    ORDER BY 
        CANTIDAD_DE_ORDENES DESC;

    -- El cliente con más órdenes tiene 37 órdenes.

3 - ¿QUIÉNES SON LOS 10 CLIENTES CON MAYORES VENTAS?
    SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    TO_CHAR(SUM(V.SALES), '9G999G999D99')
        AS VENTAS_TOTALES
