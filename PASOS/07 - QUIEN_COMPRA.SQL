11 - ¿CÓMO SE COMPARAN LOS CLIENTES EN TÉRMINOS DE VENTAS, GANANCIAS, UNIDADES, ÓRDENES Y TICKET PROMEDIO?
    SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    ROUND(SUM(V.SALES),2) AS VENTAS_TOTALES,
    ROUND(SUM(V.PROFIT),2) AS GANANCIAS_TOTALES,
    SUM(V.QUANTITY) AS UNIDADES_TOTALES,
    COUNT(DISTINCT V.ORDER_ID) AS ORDENES_TOTALES,
    ROUND(SUM (V.SALES) / COUNT(DISTINCT V.ORDER_ID),2)
            AS TICKET_PROMEDIO 
    FROM CLIENTES_SS C 
    JOIN VENTAS_SS V 
            ON V.CUSTOMER_ID = C.CUSTOMER_ID 
    GROUP BY 
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
    ORDER BY 
        GANANCIAS_TOTALES DESC, 
        VENTAS_TOTALES DESC

