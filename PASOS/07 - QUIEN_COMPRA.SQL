16 - ¿QUE SEGMENTO REALIZO MAS ORDENES?
    SELECT 
    SEGMENT,
    COUNT (V.ORDER_ID) 
    AS CANTIDAD_DE_ORDENES,
    ROUND (COUNT (V.ORDER_ID) * 100 /
    SUM(COUNT(V.ORDER_ID)) OVER (),2) --- “Toma cada conteo por grupo y súmalos todos para obtener el total general”
        AS PORCENTAJE_ORDENES
    FROM CLIENTES_SS C
    JOIN VENTAS_SS V
        ON V.CUSTOMER_ID = C.CUSTOMER_ID
    GROUP BY 
        SEGMENT
    ORDER BY 
        CANTIDAD_DE_ORDENES DESC;

