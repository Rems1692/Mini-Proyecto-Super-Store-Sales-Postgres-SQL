1 - ¿QUÉ CATEGORÍA GENERA MÁS VENTAS Y QUE PORCENTAJE REPRESENTA?
    SELECT
    P.CATEGORY,
    ROUND(SUM(V.SALES),2) AS VENTAS_TOTALES,
    ROUND(SUM(V.SALES) * 100.0/
	SUM(SUM(V.SALES)) OVER(),0)
    AS PORCENTAJE_GANANCIAS
    FROM PRODUCTOS_SSL P
    JOIN VENTAS_SS V
    ON V.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY
    P.CATEGORY
    ORDER BY
    VENTAS_TOTALES DESC;


